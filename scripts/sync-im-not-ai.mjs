import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";

const REPOSITORY = "epoko77-ai/im-not-ai";
const API = `https://api.github.com/repos/${REPOSITORY}`;
const RAW = `https://raw.githubusercontent.com/${REPOSITORY}`;
const USER_AGENT = "naver-kin-content-research-web-im-not-ai-sync";

async function fetchText(url) {
  const response = await fetch(url, {
    headers: {
      Accept: "text/plain, application/vnd.github+json",
      "User-Agent": USER_AGENT,
    },
    signal: AbortSignal.timeout(30_000),
  });

  if (!response.ok) {
    throw new Error(`${url} → HTTP ${response.status}`);
  }
  return response.text();
}

async function fetchJson(url) {
  return JSON.parse(await fetchText(url));
}

function versionFromReadme(readme) {
  const match = readme.match(/Humanize KR[^v\n]*v(\d+\.\d+\.\d+)/i);
  return match?.[1] || "unknown";
}

function compactUpstreamPolicy(quickRules) {
  const lines = quickRules.split(/\r?\n/);
  const keep = [];
  const importantIds = new Set([
    "A-1",
    "A-2",
    "A-3",
    "A-7",
    "A-8",
    "A-9",
    "A-10",
    "A-16",
    "A-18",
    "A-19",
    "A-20",
    "A-21",
    "A-24",
    "B-1",
    "B-2",
    "C-2",
    "C-5",
    "C-7",
    "C-8",
    "C-9",
    "C-10",
    "C-11",
    "D-1",
    "D-2",
    "D-3",
    "D-4",
    "D-6",
    "D-7",
    "D-8",
    "D-9",
    "D-10",
    "D-11",
    "D-12",
    "E-1",
    "E-2",
    "E-7",
    "F-4",
    "F-5",
    "F-7",
    "G-1",
    "G-2",
  ]);

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) continue;

    if (
      trimmed.startsWith("**Do-NOT") ||
      trimmed.startsWith("**서법 보존") ||
      trimmed.startsWith("**내용 앵커") ||
      trimmed.startsWith("**과윤문 가드")
    ) {
      keep.push(trimmed);
      continue;
    }

    const idMatch = trimmed.match(/^- \*\*([A-Z]-\d+)\*\*/);
    if (idMatch && importantIds.has(idMatch[1])) {
      keep.push(trimmed);
    }
  }

  if (keep.length < 20) {
    throw new Error(
      `upstream quick-rules에서 핵심 규칙을 충분히 추출하지 못했습니다 (${keep.length}개).`,
    );
  }

  return ["[im-not-ai 최신 upstream 핵심 규칙 — 자동 생성]", ...keep].join(
    "\n",
  );
}

function tsString(value) {
  return JSON.stringify(value);
}

async function main() {
  const commit = await fetchJson(`${API}/commits/main`);
  const sha = String(commit?.sha || "").trim();
  if (!/^[0-9a-f]{40}$/i.test(sha)) {
    throw new Error("im-not-ai main의 commit SHA를 확인하지 못했습니다.");
  }

  const [readme, quickRules, license] = await Promise.all([
    fetchText(`${RAW}/${sha}/README.md`),
    fetchText(`${RAW}/${sha}/skills/humanize-korean/references/quick-rules.md`),
    fetchText(`${RAW}/${sha}/LICENSE`),
  ]);

  const version = versionFromReadme(readme);
  const policy = compactUpstreamPolicy(quickRules);
  const checksum = createHash("sha256").update(quickRules).digest("hex");

  await mkdir("vendor/im-not-ai", { recursive: true });
  await writeFile(
    "vendor/im-not-ai/quick-rules.md",
    quickRules.replace(/\s+$/, "") + "\n",
    "utf8",
  );
  await writeFile(
    "vendor/im-not-ai/LICENSE",
    license.replace(/\s+$/, "") + "\n",
    "utf8",
  );
  await writeFile(
    "vendor/im-not-ai/UPSTREAM.md",
    [
      "# im-not-ai vendored snapshot",
      "",
      `- Upstream: https://github.com/${REPOSITORY}`,
      `- Version: ${version}`,
      `- Commit: ${sha}`,
      `- Quick Rules SHA256: ${checksum}`,
      "- License: MIT",
      "",
      "이 파일들은 scripts/sync-im-not-ai.mjs가 upstream main에서 자동 동기화합니다.",
      "업데이트는 회귀 테스트, ESLint, production build가 모두 통과한 경우에만 main에 반영합니다.",
      "",
    ].join("\n"),
    "utf8",
  );

  const generated = `/* AUTO-GENERATED by scripts/sync-im-not-ai.mjs. Do not edit manually. */

export const IM_NOT_AI_UPSTREAM_SOURCE = {
  repository: "https://github.com/${REPOSITORY}",
  version: ${tsString(version)},
  commit: ${tsString(sha)},
  quickRulesSha256: ${tsString(checksum)},
  license: "MIT",
} as const;

export const IM_NOT_AI_UPSTREAM_POLICY = ${tsString(policy)};
`;

  await writeFile("lib/im-not-ai-upstream-policy.ts", generated, "utf8");

  console.log(
    `[im-not-ai sync] ${version} · ${sha.slice(0, 12)} · 핵심 규칙 ${policy.split(/\n/).length - 1}개`,
  );
}

main().catch((error) => {
  console.error(
    `[im-not-ai sync] ${
      error instanceof Error ? error.message : String(error)
    }`,
  );
  process.exitCode = 1;
});
